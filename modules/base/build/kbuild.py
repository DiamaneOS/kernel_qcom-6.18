#!/usr/bin/env python3
"""kbuild.py LIST CONFIG OUTDIR [KERNEL_AUTOCONF]: Kbuild for an external-module (M=) build of the DDK modules in
modules.bzl named by LIST, with the vendor Kconfig values of CONFIG on top of the kernel's own
(KERNEL_AUTOCONF, its include/config/auto.conf). Used until the DDK build takes over: it reads
the same registry.

modules.bzl uses the CodeLinaro registry format (register_modules(registry), one
registry.register() per ddk_module). This script evaluates it the way the DDK macros do for
srcs, conditional_srcs, includes, local_defines and copts, and writes:
  Kbuild (tree root, ignored by git)  obj-m lines, objects and per-object flags
  OUTDIR/vendor_autoconf.h           the vendor CONFIG values as C defines
  OUTDIR/modules.tsv                 module, registry name, objects
Headers: the vendor include directories come before the kernel's, as the DDK headers do.
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def load_registry():
    mods = []

    class Registry:
        def register(self, **kw):
            mods.append(kw)

    g = {'select': lambda d: d.get('//conditions:default', []), 'True': True, 'False': False}
    src = open(os.path.join(ROOT, 'modules.bzl')).read()
    exec(compile(src, 'modules.bzl', 'exec'), g)
    g['register_modules'](Registry())
    return {m['name']: m for m in mods}


def read_config(path):
    cfg = {}
    for line in open(path):
        line = line.strip()
        m = re.match(r'^(CONFIG_\w+)=(.*)$', line)
        if m:
            cfg[m.group(1)] = m.group(2)
            continue
        m = re.match(r'^# (CONFIG_\w+) is not set$', line)
        if m:
            cfg[m.group(1)] = 'n'
    return cfg


def main():
    listp, cfgp, out = sys.argv[1:4]
    kcfg = read_config(sys.argv[4]) if len(sys.argv) > 4 else {}
    reg = load_registry()
    names = [l.split('#')[0].strip() for l in open(listp)]
    names = [n for n in names if n]
    cfg = read_config(cfgp)
    for n in names:
        m = reg.get(n)
        if not m:
            sys.exit(f'{n}: not in modules.bzl')
        c = m.get('config')
        if c and cfg.get(c) not in ('y', 'm'):
            sys.exit(f'{n}: {c} is not enabled in {cfgp}')
    on = lambda k: cfg.get(k, kcfg.get(k)) in ('y', 'm')
    lines = ['# Generated by build/kbuild.py from modules.bzl. Do not edit.',
             'LINUXINCLUDE := -I$(VENDOR_ROOT)/arch/arm64/include -I$(VENDOR_ROOT)/include '
             '-I$(VENDOR_ROOT)/include/uapi $(LINUXINCLUDE) -I$(VENDOR_ROOT)',
             'ccflags-y += -include $(VENDOR_OUT)/vendor_autoconf.h']
    table = []
    for n in names:
        m = reg[n]
        out_ko = m['out'][:-3]
        srcs = list(m.get('srcs', []))
        for k, d in (m.get('conditional_srcs') or {}).items():
            srcs += d.get(on(k), [])
        objs = [s[:-2] + '.o' for s in srcs if s.endswith(('.c', '.S'))]
        dirs = []
        for s in srcs + [x for dep in m.get('deps', []) if dep in reg for x in reg[dep].get('srcs', [])]:
            d = os.path.dirname(s)
            if d not in dirs:
                dirs.append(d)
        flags = ['-I$(VENDOR_ROOT)/' + i for i in m.get('includes', [])]
        flags += ['-I$(VENDOR_ROOT)/' + d for d in dirs]
        flags += ['-D' + d for d in m.get('local_defines', [])]
        flags += list(m.get('copts', []))
        lines.append(f'obj-m += {out_ko}.o')
        lines.append(f'{out_ko}-y := ' + ' '.join(objs))
        for o in objs:
            # make starts a comment at '#' (as in -Wno-#pragma-messages)
            lines.append(f'CFLAGS_{o} += ' + ' '.join(flags).replace('#', '\\#'))
        table.append(f'{out_ko}.ko\t{n}\t{" ".join(objs)}')
    os.makedirs(out, exist_ok=True)
    open(os.path.join(ROOT, 'Kbuild'), 'w').write('\n'.join(lines) + '\n')
    hdr = ['/* Generated by build/kbuild.py: vendor Kconfig values. Do not edit. */']
    for k, v in sorted(cfg.items()):
        if v == 'n':
            continue
        if v == 'y':
            hdr.append(f'#define {k} 1')
        elif v == 'm':
            hdr.append(f'#define {k}_MODULE 1')
        else:
            hdr.append(f'#define {k} {v}')
    open(os.path.join(out, 'vendor_autoconf.h'), 'w').write('\n'.join(hdr) + '\n')
    open(os.path.join(out, 'modules.tsv'), 'w').write('\n'.join(table) + '\n')
    print(f'{len(names)} modules')


if __name__ == '__main__':
    main()

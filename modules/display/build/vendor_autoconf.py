#!/usr/bin/env python3
# vendor_autoconf.py CORE_CONFIG DEFCONFIG...: the vendor CONFIG_ values of the defconfigs as an autoconf
# header, for symbols the core configuration leaves unset (vendor modules may build core drivers the
# GKI build leaves out, such as arm-smmu). Later files win.
import sys
core = set()
for l in open(sys.argv[1]):
    if l.startswith('CONFIG_'):
        core.add(l.split('=', 1)[0])
vals = {}
for f in sys.argv[2:]:
    try:
        lines = open(f).read().splitlines()
    except FileNotFoundError:
        continue
    for l in lines:
        if l.startswith('CONFIG_'):
            k, v = l.split('=', 1)
            vals[k] = v
        elif l.startswith('# CONFIG_') and l.endswith(' is not set'):
            vals[l[2:].split()[0]] = 'n'
print('/* Generated by vendor_autoconf.py. */')
for k in sorted(vals):
    if k in core:
        continue
    v = vals[k]
    if v == 'y':
        print(f'#define {k} 1')
    elif v == 'm':
        print(f'#define {k}_MODULE 1')
    elif v != 'n':
        print(f'#define {k} {v}')
